SURNAMES = list("김이박최정강조윤장임한오서신권황안송류홍")
GIVEN = ["민준", "서연", "지호", "하윤", "도윤", "서아", "시우", "지유", "예준", "수아", "주원", "채원", "건우", "다은", "현우", "지안"]
VOLUME = {3: 11, 9: 9, 6: 8, 7: 8, 2: 7, 12: 7}      # 달별 건수(나머지는 5)
SEASON_SHARE = 0.75                                   # 그 달 민원 중 계절 문장 비율


def seasonal_rows(today=None, seed=7):
    """반환: seed_demo_db가 읽는 형식의 dict 목록(오래된 순). 모두 처리 완료, 처리 기간은 기한 안."""
    today = today or date.today()
    rng = random.Random(seed)
    names = [s + g for s in SURNAMES for g in GIVEN]
    rng.shuffle(names)
    rows, n = [], 0
    y, m = today.year - 1, 3
    while (y, m) <= (today.year, today.month - 1 if today.month > 1 else 12):
        for _ in range(VOLUME.get(m, 5)):
            pool = SEASON[m] if rng.random() < SEASON_SHARE else BACKGROUND
            day = date(y, m, rng.randint(1, 28))
            ago = (today - day).days
            if ago < 25:                       # 최근 25일은 기본 예시 데이터(demo_db.jsonl)가 맡는다
                continue
            rows.append({"student": names[n % len(names)], "class_no": f"{rng.randint(1, 3)}{rng.randint(0, 1)}{rng.randint(1, 9)}",
                         "text": rng.choice(pool), "days_ago": ago, "status": "완료", "done_after_days": 0.5, "actor": "담당자",
                         "memo": "", "homeroom_sent": False})
            n += 1
        m += 1
        if m == 13:
            y, m = y + 1, 1
    return sorted(rows, key=lambda r: -r["days_ago"])
